"""Offline differential tests. Expected results are derived from pinned static
instructions, not generated by running Sony code or a physical player.
"""
from dataclasses import asdict, replace
import ast
import json
from pathlib import Path
import unittest
from firmware_research.fwupdater_model import (
    ACCEPTED_ACTIVATION_STATUS, Config, Scenario, SafetyEvidence, CapturedDevice,
    select_captured_a91x, version_prompt,
    file_error, proposed_decision, replay,
)


class OfficialFlowReplayTests(unittest.TestCase):
    def operations(self, result):
        return [event.operation for event in result.events]

    def test_model_product_and_vendor_specific_subidentification_selection(self):
        def frame(model):
            raw = bytearray(128)
            raw[24:40] = model.encode('ascii').ljust(16, b' ')
            return bytes(raw)
        for model in ['NW-A916', 'NW-A918', 'NW-A919']:
            raw = frame(model)
            self.assertEqual(select_captured_a91x([CapturedDevice(raw)]), (model, None))
            changed_subrevision = bytearray(raw)
            changed_subrevision[44:48] = b'IW14'
            self.assertEqual(select_captured_a91x([CapturedDevice(bytes(changed_subrevision))]), (model, None))
            wrong_subid = bytearray(raw)
            wrong_subid[96] = 1
            self.assertEqual(select_captured_a91x([CapturedDevice(bytes(wrong_subid))])[1], 0x80042200)
        self.assertEqual(select_captured_a91x([])[1], 0x80042200)
        self.assertEqual(select_captured_a91x([CapturedDevice(frame('NW-A918')), CapturedDevice(frame('NW-A919'))])[1], 0x80042201)
        self.assertEqual(select_captured_a91x([CapturedDevice(frame('NW-A918'), pid=0xFFFF)])[1], 0x80042200)
        self.assertEqual(select_captured_a91x([CapturedDevice(frame('NW-OTHER'))])[1], 0x80042200)
        with self.assertRaises(ValueError):
            select_captured_a91x([CapturedDevice(bytes(127))])

    def test_official_same_version_and_downgrade_are_confirmation_branches(self):
        for current, target, resource in [('1.02', '1.03', 202), ('1.03', '1.03', 203), ('1.03', '1.02', 204)]:
            self.assertEqual(version_prompt(current, target, True), (resource, True))
            self.assertEqual(version_prompt(current, target, False), (resource, False))
            self.assertEqual(version_prompt(current, target, 'true'), (resource, False))

    def test_replay_constants_and_com_route_match_pinned_static_evidence(self):
        import hashlib
        evidence = Path(__file__).resolve().parents[1] / 'docs/audits/fwupdater-flow-2026-10-19/static-expanded'
        facts = json.loads((evidence / 'facts.json').read_text(encoding='utf-8'))
        bindings = {row['interface']: row for row in facts['com_bindings']}
        self.assertEqual(bindings['transfer']['object_offset'], 8)
        self.assertEqual(bindings['transfer']['slots']['0xc'], '0x1000b600')
        self.assertEqual(bindings['updater']['slots']['0x1c'], '0x1000b6e0')
        self.assertEqual(bindings['device']['slots']['0x2c'], '0x1000a180')
        self.assertEqual(Config().timer_ms, facts['timer_seconds'] * 1000)
        self.assertEqual(Config().timeout_ms, facts['timeout_seconds_when_absent'] * 1000)
        self.assertEqual(ACCEPTED_ACTIVATION_STATUS, int(facts['activation_false_result_accepted_packed_status'], 16))
        for error in [112, 5, 23]:
            expected = facts['copy_error_map'].get(str(error), facts['copy_error_map']['other'])
            self.assertEqual(file_error(error), int(expected, 16))
        self.assertIn('same version', facts['version_confirmations_en_US']['203'].lower())
        self.assertIn('older version', facts['version_confirmations_en_US']['204'].lower())

    def test_private_export_hashes_when_local_evidence_is_available(self):
        import hashlib
        evidence = Path(__file__).resolve().parents[1] / 'docs/audits/fwupdater-flow-2026-10-19/static-expanded'
        facts = json.loads((evidence / 'facts.json').read_text(encoding='utf-8'))
        if not all((evidence/row['file']).is_file() for row in facts['disassembly']):
            self.skipTest('Private Sony analysis exports are not distributed; hash replay not run')
        for row in facts['disassembly']:
            self.assertEqual(hashlib.sha256((evidence / row['file']).read_bytes()).hexdigest(), row['sha256'])

    def test_actual_ini_timer_and_shared_deadline(self):
        cfg = Config.from_timer()
        self.assertEqual((cfg.timer_ms, cfg.timeout_ms, cfg.battery_threshold), (100000, 150000, -1))
        self.assertEqual(Config.from_timer('0:03').timeout_ms, 4000)
        self.assertEqual(Config.from_timer(timeout='2:01').timeout_ms, 121000)
        self.assertEqual(Config.from_timer('1:00', '3:00').timeout_ms, 180000)

    def test_source_derived_golden_traces(self):
        fixtures = Path(__file__).parent / 'firmware_research' / 'golden_traces.json'
        for case in json.loads(fixtures.read_text(encoding='utf-8')):
            with self.subTest(case=case['name']):
                result = replay(Scenario(name=case['name'], **case['scenario']))
                self.assertEqual(result.outcome, case['outcome'])
                self.assertEqual(result.elapsed_ms, case['elapsed_ms'])
                self.assertEqual(result.activation_count, case['activation_count'])
                self.assertEqual([(e.elapsed_ms, e.operation, e.detail) for e in result.events
                                  if e.operation in case['selected_operations']],
                                 [tuple(row) for row in case['expected_events']])

    def test_copy_win32_errors_are_mapped_and_stop_activation(self):
        for error, expected in [(112, 0x80047008), (5, 0x80047007), (23, 0x80047006)]:
            result = replay(Scenario(copy_winerror=error))
            self.assertEqual((result.outcome, result.hresult), ('copy_failed', expected))
            self.assertEqual(result.activation_count, 0)
            self.assertIn('delete_staged_package', self.operations(result))
            self.assertNotIn('read_installed_numeric_version', self.operations(result))

    def test_cleanup_can_mask_original_copy_error_in_legacy_worker(self):
        result = replay(Scenario(copy_winerror=112, delete_winerror=5))
        self.assertEqual((result.outcome, result.hresult), ('cleanup_failed', 0x80047007))
        self.assertEqual(result.activation_count, 0)

    def test_missing_empty_and_initial_identity_fail_before_activation(self):
        for scenario, outcome in [(Scenario(source_kind='missing'), 'source_missing'),
                                  (Scenario(source_bytes=0), 'empty_source'),
                                  (Scenario(initial_snapshot_matches=False), 'initial_identity_failed')]:
            result = replay(scenario)
            self.assertEqual(result.outcome, outcome)
            self.assertEqual(result.activation_count, 0)
        self.assertNotIn('delete_staged_package', self.operations(replay(Scenario(source_kind='missing'))))

    def test_free_space_is_source_plus_integer_one_twentieth(self):
        for size in [1, 19, 20, 99, 100, 13734432]:
            threshold = size + size // 20
            result = replay(Scenario(source_bytes=size, free_bytes=threshold - 1))
            self.assertEqual(result.outcome, 'insufficient_data_volume_space')
            self.assertEqual(result.activation_count, 0)
            self.assertEqual(replay(Scenario(source_bytes=size, free_bytes=threshold)).activation_count, 1)

    def test_space_and_measure_failures_never_activate(self):
        for scenario, expected in [(Scenario(free_space_winerror=112), 0x80047008),
                                   (Scenario(measure_hresult=0x80047006), 0x80047006)]:
            result = replay(scenario)
            self.assertEqual(result.hresult, expected)
            self.assertEqual(result.activation_count, 0)

    def test_legacy_ignores_hash_corruption_when_os_copy_reports_success(self):
        # Conditional diagnostic: supplied version readback still matches. This
        # does NOT claim a player would accept or boot a corrupted payload.
        result = replay(Scenario(staged_hash_matches=False))
        self.assertEqual(result.outcome, 'numeric_version_matched')
        self.assertEqual(result.activation_count, 1)
        self.assertEqual(proposed_decision(SafetyEvidence(staged_hash_verified=False)), 'blocked_before_activation')

    def test_known_activation_false_return_exceptions_are_explicit(self):
        for status in [0, ACCEPTED_ACTIVATION_STATUS]:
            result = replay(Scenario(activation_ok=False, packed_status=status))
            self.assertIn('legacy_false_transport_result_tolerated', self.operations(result))
            self.assertEqual(result.activation_count, 1)
        for scenario, expected in [(Scenario(activation_ok=False, drive_index_valid=False), 0x80047002),
                                   (Scenario(activation_ok=False, packed_status=0xFF030000), 0x80047001)]:
            result = replay(scenario)
            self.assertEqual(result.hresult, expected)
            self.assertEqual(result.activation_count, 1)
            self.assertNotIn('presence', self.operations(result))
        self.assertEqual(proposed_decision(SafetyEvidence(activation_ambiguous=True)),
                         'review_no_resend_no_delete_no_other_device_writes')

    def test_default_battery_query_is_skipped_but_configured_threshold_is_enforced(self):
        self.assertNotIn('power_query', self.operations(replay()))
        cfg = Config.from_timer(battery_threshold=30)
        result = replay(Scenario(battery_percent=29), cfg)
        self.assertEqual(result.outcome, 'battery_below_configured_threshold')
        self.assertEqual(result.activation_count, 0)
        result = replay(Scenario(power_error=0x80047001), cfg)
        self.assertEqual(result.outcome, 'power_query_failed')
        self.assertEqual(proposed_decision(SafetyEvidence(power_policy_verified=False)), 'blocked_before_activation')

    def test_legacy_raw_unknown_255_is_not_a_native_battery_authorization(self):
        result = replay(Scenario(battery_percent=255), Config.from_timer(battery_threshold=30))
        self.assertEqual(result.activation_count, 1)
        self.assertEqual(proposed_decision(SafetyEvidence()), 'blocked_before_activation')

    def test_tick_wrap_does_not_reset_elapsed_deadline(self):
        normal = replay(Scenario())
        wrapped = replay(Scenario(tick_start=0xFFFFFF00))
        self.assertEqual(asdict(normal), asdict(wrapped))

    def test_reopen_retries_and_snapshot_mismatch_never_signal_completion(self):
        retry = replay(Scenario(open_failures=2))
        self.assertEqual(retry.outcome, 'numeric_version_matched')
        self.assertEqual(self.operations(retry).count('open_and_compare_snapshot'), 3)
        for scenario in [Scenario(open_failures=10), Scenario(readback_snapshot_matches=False)]:
            result = replay(scenario)
            self.assertEqual(result.outcome, 'reopen_exhausted')
            self.assertEqual(self.operations(result).count('open_and_compare_snapshot'), 10)
            self.assertNotIn('completion_message_401', self.operations(result))

    def test_100_percent_precedes_cleanup_and_version_check(self):
        for scenario, outcome in [(Scenario(version_error=0x80047001), 'version_query_failed'),
                                  (Scenario(installed_version='1.02'), 'installed_version_mismatch'),
                                  (Scenario(delete_winerror=5), 'cleanup_failed'),
                                  (Scenario(reopen_before_cleanup_hresult=0x80047002), 'reopen_before_cleanup_failed')]:
            result = replay(scenario)
            self.assertEqual(result.outcome, outcome)
            self.assertTrue(any(e.operation == 'progress' and e.detail == '100' for e in result.events))
            self.assertNotIn('completion_message_401', self.operations(result))
        good = replay()
        ops = self.operations(good)
        self.assertLess(ops.index('delete_staged_package'), ops.index('read_installed_numeric_version'))

    def test_stat_retry_exhaustion_itself_is_not_a_legacy_abort(self):
        result = replay(Scenario(stat_failures=10))
        self.assertEqual(self.operations(result).count('stat_staged_path'), 10)
        self.assertIn('delete_staged_package', self.operations(result))
        self.assertEqual(result.outcome, 'numeric_version_matched')

    def test_strict_policy_does_not_infer_full_build_from_numeric_version(self):
        supplied = SafetyEvidence(exact_identity=True, power_policy_verified=True,
                                  staged_hash_verified=True, candidate_qualified=True,
                                  recovery_verified=True, durable_intent=True)
        self.assertEqual(proposed_decision(supplied, after_activation=True), 'review_no_success_no_delete')
        self.assertEqual(proposed_decision(replace(supplied, full_build_readback=True), after_activation=True),
                         'simulated_requirements_met_live_executor_still_disabled')
        self.assertEqual(proposed_decision(replace(supplied, unresolved_activation_intent=True)),
                         'review_no_resend_no_delete_no_other_device_writes')

    def test_every_required_evidence_gap_blocks_activation(self):
        complete = SafetyEvidence(exact_identity=True, power_policy_verified=True,
                                  staged_hash_verified=True, candidate_qualified=True,
                                  recovery_verified=True, durable_intent=True)
        for field in ['exact_identity', 'power_policy_verified', 'staged_hash_verified',
                      'candidate_qualified', 'recovery_verified', 'durable_intent']:
            self.assertEqual(proposed_decision(replace(complete, **{field: False})), 'blocked_before_activation')

    def test_unknown_paths_are_explicit_and_never_activate(self):
        self.assertEqual(replay(Scenario(source_kind='directory')).outcome, 'unmodeled_directory_or_source_kind')
        self.assertEqual(replay(config=Config(command_type=1)).outcome, 'unmodeled_command_type')
        with self.assertRaises(ValueError):
            Config.from_timer('0:00')

    def test_fault_sweep_is_bounded_and_never_resends_or_enables_hardware(self):
        for copy_ms in [0, 500, 100000, 150000, 151000]:
            for disconnect in [None, 0, 2000, 8000, 160000]:
                for reconnect in [None, 10000, 150000, 151000, 160000]:
                    if reconnect is not None and disconnect is not None and reconnect < disconnect:
                        continue
                    result = replay(Scenario(copy_ms=copy_ms, disconnect_at_ms=disconnect, reconnect_at_ms=reconnect))
                    self.assertLessEqual(result.activation_count, 1)
                    self.assertFalse(result.firmware_write_enabled)
                    self.assertLess(len(result.events), 500)

    def test_replay_module_has_no_transport_or_io_imports(self):
        path = Path(__file__).parent / 'firmware_research' / 'fwupdater_model.py'
        tree = ast.parse(path.read_text(encoding='utf-8'))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                self.fail('Only dataclasses import is permitted in the pure model')
            if isinstance(node, ast.ImportFrom):
                self.assertEqual(node.module, 'dataclasses')
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
                self.assertNotIn(node.func.id, ['open', 'exec', 'eval', '__import__', 'compile'])


if __name__ == '__main__':
    unittest.main()
